-- 22. 시연 장소 — 측정이 적어도 단계를 보여주는 장소 목록
--     먼저 필요: 005 (settings), seed/places_hongdae.sql
--
--     예측 규칙은 "같은 요일 묶음(평일/주말) · 같은 시각에 측정 3건 이상이어야 단계" 다.
--     10/18(일) 답사 7건은 장소당 1~2건이라 이 규칙으로는 주말 15~16시에 '후보'(점선)까지만
--     나오고 평일에는 아무것도 안 뜬다. 추가 측정을 나가기 어려워 시연 장소 5곳만 예외를 둔다.
--
--     목록에 든 장소는
--       - 평일 · 주말을 가리지 않고 모든 측정을 쓴다
--       - 1건이어도 단계(무던함 · 보통 · 부담 높음)로 표시한다
--       - 측정 없는 시각은 추정하지 않고 정보 부족으로 둔다 (측정한 시각만 단계)
--     그 밖의 장소는 원래 규칙 그대로다. 목록을 비우면('[]') 예외가 사라진다.
--     시연용이다. 측정이 쌓이면 비운다.

insert into settings (key, value, description) values
  ('demo_places', '[12, 13, 14, 15, 16]'::jsonb,
   '시연 장소. 요일 묶음을 가리지 않고 1건이어도 단계로 표시한다. 비우면 원래 규칙(요일 구분 · 3건 이상)')

on conflict (key) do update
  set value       = excluded.value,
      description = excluded.description,
      updated_at  = now();
