-- 21. 기준 기종을 갤럭시(안드로이드 센서)로, 기종 보정값, 눈금 단위 변경
--     먼저 필요: 019 (score_sound_level · score_light)
--
--     점수 눈금은 지금까지 아이폰 15 로 잰 답사 7건으로 정해져 있었다.
--     앱은 안드로이드에서만 돌고, 소리는 마이크 원신호, 밝기는 조도센서로 잰다.
--     아이폰 카메라식 조도는 "무엇을 겨눴나" 에 따라 2~5배까지 달라져서
--     (10/26 같은 자리: 천장을 보면 462, 흰 종이를 보면 1860) 기준으로 쓸 수 없다.
--     그래서 기준을 갤럭시 Z플립7 (SM-F766N) 로 바꾸고, 아이폰 7건 쪽에 보정을 붙인다.
--
--     보정값은 "갤럭시 기준으로 바꾸려면" 이다.
--       db  : 더한다.  아이폰 15 는 같은 소리를 1.2dB 높게 적는다 → −1.2
--             (10/26 거실 26분 동시 녹음. 30초 Leq 차이 ±1.0, 소리 크기와 무관하게 일정. 확정)
--       lux : 곱한다.  아이폰 카메라 값은 갤럭시 센서의 약 2배 → ×0.5
--             (10/26 같은 방을 돌며 잰 두 폰의 값 분포 비교, 중앙값 915 ↔ 445. 임시값.
--              답사 장소를 갤럭시 센서로 다시 재면 7건 조도를 그 값으로 바꾸고 이 보정은 지운다)
--
--     키는 measurements.device_model (안드로이드 Build.MODEL) 의 앞부분과 맞으면 된다.
--     목록에 없는 안드로이드 기종은 보정 없이 계산하고 batch 가 경고를 남긴다.

insert into settings (key, value, description) values
  ('device_offsets',
   '{"SM-F766": {"db": 0, "lux": 1.0}, "iPhone 15": {"db": -1.2, "lux": 0.5}}'::jsonb,
   '기종별 보정값. 기준은 갤럭시 SM-F766 (안드로이드 센서). 다른 기종 측정은 db 를 더하고 lux 를 곱해 기준으로 바꾼다. 키는 device_model 앞부분')

on conflict (key) do update
  set value       = excluded.value,
      description = excluded.description,
      updated_at  = now();


-- -----------------------------------------------------
-- 눈금을 갤럭시 단위로 (결과 점수는 그대로)
-- -----------------------------------------------------
--
-- 소리: 아이폰 단위 50→0 · 73→100 을 −1.2 하면 48.8 → 71.8.
-- 밝기: 아이폰 단위 150→0 · 2000→100 은 마트(1300~1900)를 밝기만으로 부담 높음(83~98)으로
--       만들어 소리 · 혼잡과 상관없이 모든 마트가 부담 높음이 됐다. 답사 느낌은 "보통".
--       끝을 6000(흐린 날 창가 수준)으로 올리면 카페 20~35(무던함), 마트 59~69(보통).
--       이것을 갤럭시 단위(×0.5)로 적으면 75 → 0점, 3000 → 100점.
--       밝기에 민감한 아이는 "우리 아이 맞춤" 에서 밝은 조명을 '매우' 로 골라 주의로 잡는다.

update settings
   set value       = '{"db_zero": 48.8, "db_full": 71.8}'::jsonb,
       description = '소리 크기 → 점수. Leq(에너지 평균) 48.8dB 가 0점, 71.8dB 가 100점, 사이는 직선. 갤럭시 SM-F766 기준. 10/24 답사 느낌에 맞춘 임시값',
       updated_at  = now()
 where key = 'score_sound_level';

update settings
   set value       = '{"lux_zero": 75, "lux_full": 3000}'::jsonb,
       description = '밝기 → 점수. 조도 중앙값 75 lux 가 0점, 3000 lux 가 100점, 사이는 로그. 갤럭시 조도센서 기준. 10/26 답사 느낌에 맞춘 임시값',
       updated_at  = now()
 where key = 'score_light';
